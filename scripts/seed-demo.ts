/**
 * Every id this script writes, derived from one prefix.
 *
 * The demo owner id is imported from src/lib/server/judge rather than declared
 * again here, so the seeded rows and the judge read path can never disagree
 * about who owns them. The other ids follow the same obviously synthetic shape,
 * and they are fixed rather than random for one reason: a re run has to land on
 * the same rows and the same object paths, or the storage bucket fills with
 * orphans and the looks stop pointing at the garments they were composed from.
 */
const DEMO_ID_PREFIX = "00000000-0000-4000-8000-";

/** Blocks keep the id families apart and readable at a glance. */
const ID_BLOCK = {
  root: 0x0,
  garment: 0x1,
  look: 0x2,
  render: 0x3,
  analysis: 0x4,
} as const;

export function demoUuid(block: number, index: number): string {
  const suffix = (block * 0x100 + index).toString(16).padStart(12, "0");
  return `${DEMO_ID_PREFIX}${suffix}`;
}


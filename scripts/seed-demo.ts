export interface SeedArgs {
  readonly mode: SeedMode;
  readonly goldenDir: string | null;
  /** The same selfie the golden run was given, since the run never copies it. */
  readonly imagePath: string | null;
  readonly dryRun: boolean;
}

export const USAGE = [
  "Usage:",
  "  npm run seed:demo -- --from-fixtures [--dry-run]",
  "  npm run seed:demo -- --from-golden <dir> [--image <path>] [--dry-run]",
  "",
  "  --from-fixtures   Seed the checked in demo fixture. No capture, no analyses, no renders.",
  "  --from-golden     Seed everything, reading the golden run output in <dir>.",
  "  --image           The selfie the golden run was given. Only needed when <dir> holds no capture.<ext>.",
  "  --dry-run         Print every row and object that would be written. Touches nothing, needs no keys.",
].join("\n");

function valueFor(flag: string, next: string | undefined): string {
  if (next === undefined || next.length === 0 || next.startsWith("--")) {
    throw new SeedError("read arguments", `${flag} needs a value.`);
  }
  return next;
}

export function parseArgs(argv: readonly string[]): SeedArgs {
  let mode: SeedMode | null = null;
  let goldenDir: string | null = null;
  let imagePath: string | null = null;
  let dryRun = false;

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--from-fixtures") {
      mode = "fixtures";
      continue;
    }
    if (arg === "--from-golden") {
      mode = "golden";
      goldenDir = valueFor(
        "--from-golden needs the directory the golden run wrote. It",
        argv[index + 1],
      );
      index += 1;
      continue;
    }
    if (arg === "--image") {
      imagePath = valueFor("--image", argv[index + 1]);
      index += 1;
      continue;
    }
    if (arg === "--dry-run") {
      dryRun = true;
      continue;
    }
    throw new SeedError("read arguments", `Unknown argument "${String(arg)}".`);
  }

  if (mode === null) {
    throw new SeedError(
      "read arguments",
      "Pick a mode: --from-fixtures or --from-golden <dir>.",
    );
  }
  return { mode, goldenDir, imagePath, dryRun };
}

/**
 * Everything --from-golden needs, read once, before a single row is written.
 *
 * Reading it all up front is deliberate: a missing file is then a failure that
 * wrote nothing, rather than one that stopped halfway through the profile.
 */
export function loadGoldenRun(args: {
  readonly source: FileSource;
  readonly imagePath: string | null;
}): GoldenInput {
  const manifest = loadGoldenManifest(args.source);
  const summaries = loadGoldenSummaries(args.source, manifest);
  const captureImagePath = findCaptureImage(args.source, args.imagePath);
  const notes: string[] = [];
  if (args.imagePath === null) {
    notes.push(
      `The selfie was found at ${captureImagePath} inside the run folder. The golden run records the hash but never copies the file, so check that this is the same image.`,
    );
  }
  return { manifest, summaries, captureImagePath, source: args.source, notes };
}

// ---------------------------------------------------------------------------
// Entry point
// ---------------------------------------------------------------------------

async function main(argv: readonly string[]): Promise<number> {
  let args: SeedArgs;
  try {
    args = parseArgs(argv);
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    console.error("");
    console.error(USAGE);
    return 1;
  }

  console.log("Seeding the demo profile");
  console.log(`Mode: ${args.mode}${args.dryRun ? " (dry run)" : ""}`);

  let golden: GoldenInput | null = null;
  let writer: SeedWriter;

  try {
    if (args.mode === "golden") {
      const dir = resolveGoldenDir(args.goldenDir);
      golden = loadGoldenRun({
        source: diskSource(dir),
        imagePath:
          args.imagePath === null
            ? null
            : resolve(process.cwd(), args.imagePath),
      });
      const succeeded = golden.manifest.calls.filter(
        (call) => call.state === "succeeded",
      );
      console.log(`Golden run directory: ${dir}`);
      console.log(
        `Recorded on ${golden.manifest.recordedOn}, ${String(succeeded.length)} succeeded call(s): ${succeeded.map((call) => call.step).join(", ")}`,
      );
    }

    if (args.dryRun) {
      writer = noopWriter();
      console.log("Dry run: no environment is read and nothing is written.");
    } else {
      const applied = loadEnvFile(resolve(process.cwd(), ".env.local"));
      console.log(
        `Loaded ${String(applied)} value(s) from .env.local. No value is ever printed.`,
      );
      const env = readSeedEnv();
      console.log(`Project: ${originOf(env.NEXT_PUBLIC_SUPABASE_URL)}`);
      writer = supabaseWriter(
        createClient<Database, "public">(
          env.NEXT_PUBLIC_SUPABASE_URL,
          env.SUPABASE_SERVICE_ROLE_KEY,
          {
            auth: {
              persistSession: false,
              autoRefreshToken: false,
              detectSessionInUrl: false,
            },
          },
        ),
      );
    }
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    console.error("Nothing was written.");
    return 1;
  }

  console.log("");
  const report = await runSeed({
    writer,
    mode: args.mode,
    golden,
    dryRun: args.dryRun,
    log: (line) => {
      console.log(line);
    },
  });

  for (const line of summaryLines(report)) {
    if (report.ok) {
      console.log(line);
    } else {
      console.error(line);
    }
  }

  return exitCodeForReport(report);
}

/** The golden run directory, absolute, so every later message names one path. */
function resolveGoldenDir(goldenDir: string | null): string {
  if (goldenDir === null) {
    throw new SeedError(
      "read arguments",
      "--from-golden needs the directory holding manifest.json.",
    );
  }
  return isAbsolute(goldenDir) ? goldenDir : resolve(process.cwd(), goldenDir);
}

/** The writer a dry run uses. It is never called, and says so if it ever is. */
function noopWriter(): SeedWriter {
  const refuse = (operation: string): never => {
    throw new SeedError(operation, "A dry run must not write.");
  };
  return {
    deleteOwnedRows: () => refuse("delete rows"),
    insertRows: () => refuse("insert rows"),
    listObjects: () => refuse("list objects"),
    removeObjects: () => refuse("remove objects"),
    putObject: () => refuse("upload object"),
  };
}

/*
 * Run only when this file is the process entry point. Importing it from a test
 * must not seed anything, which is what makes the unit tests possible.
 */
const invokedDirectly =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (invokedDirectly) {
  main(process.argv.slice(2))
    .then((code) => {
      process.exitCode = code;
    })
    .catch((error: unknown) => {
      console.error(error instanceof Error ? error.message : String(error));
      console.error("Nothing further was written.");
      process.exitCode = 1;
    });
}

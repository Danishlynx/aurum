export interface RunSeedOptions {
  readonly writer: SeedWriter;
  readonly mode: SeedMode;
  readonly golden: GoldenInput | null;
  readonly dryRun: boolean;
  readonly log: (line: string) => void;
}

/**
 * Walks the plan in order and reports what landed.
 *
 * Never throws. A failure stops the run, marks the step that failed, leaves
 * every later step as "not run", and comes back with ok false, so the caller
 * can print one summary that says what was written and what was not.
 */
export async function runSeed(options: RunSeedOptions): Promise<SeedReport> {
  const steps: StepReport[] = SEED_PLAN.map((step) => ({
    id: step.id,
    title: step.title,
    status: "not run",
    rows: 0,
    objects: 0,
    note: "",
  }));
  const byId = new Map(steps.map((step) => [step.id, step] as const));

  const log = options.log;
  const golden = options.mode === "golden" ? options.golden : null;

  const step = (id: string): StepReport => {
    const found = byId.get(id);
    if (found === undefined) {
      throw new SeedError("run seed", `Unknown step "${id}".`);
    }
    return found;
  };

  const putAll = async (objects: readonly SeedObject[]): Promise<void> => {
    for (const object of objects) {
      if (!options.dryRun) {
        await options.writer.putObject(object);
      }
      log(`      ${object.bucket}/${object.path} (${object.contentType})`);
    }
  };

  const insert = async <T extends SeedTableName>(
    table: T,
    rows: readonly Insert<T>[],
  ): Promise<void> => {
    if (!options.dryRun) {
      await options.writer.insertRows(table, rows);
    }
    log(`      ${String(rows.length)} row(s) into public.${table}`);
  };

  let failure: string | null = null;

  try {
    // 1. owner ---------------------------------------------------------------
    {
      const current = step("owner");
      log("[1/9] Demo owner");
      if (DEMO_OWNER_ID !== demoUuid(ID_BLOCK.root, 1)) {
        throw new SeedError(
          "check demo owner",
          `DEMO_OWNER_ID in src/lib/server/judge is "${DEMO_OWNER_ID}", which is not the id this script derives its other ids from. Keep the two in step.`,
        );
      }
      log(`      owner id: ${DEMO_OWNER_ID}`);
      log(`      ${NO_PROFILES_ROW_NOTE}`);
      current.status = "skipped";
      current.note = NO_PROFILES_ROW_NOTE;
    }

    // 2. clear ---------------------------------------------------------------
    {
      const current = step("clear");
      log("[2/9] Clearing anything already owned by the demo id");
      let removed = 0;
      for (const bucket of Object.values(BUCKETS)) {
        const existing = options.dryRun
          ? []
          : await options.writer.listObjects(bucket, DEMO_OWNER_ID);
        if (!options.dryRun && existing.length > 0) {
          await options.writer.removeObjects(bucket, existing);
        }
        removed += existing.length;
        log(`      ${bucket}: ${String(existing.length)} object(s) removed`);
      }
      for (const table of DELETE_ORDER) {
        if (!options.dryRun) {
          await options.writer.deleteOwnedRows(table, DEMO_OWNER_ID);
        }
        log(`      public.${table}: rows for the demo owner deleted`);
      }
      current.status = options.dryRun ? "skipped" : "written";
      current.objects = removed;
      current.note = options.dryRun
        ? "Dry run. Nothing was deleted."
        : "Delete then insert, so a re run lands on exactly the current fixture.";
    }

    // 3. capture -------------------------------------------------------------
    let captureWritten = false;
    {
      const current = step("capture");
      log("[3/9] Capture");
      if (golden === null) {
        current.status = "skipped";
        current.note =
          "No photo exists in fixtures mode, so no capture row and no object. The profile row keeps capture_id null.";
        log(`      ${current.note}`);
      } else {
        const seed = buildCaptureSeed(golden);
        await putAll([seed.object]);
        await insert("captures", [seed.row]);
        captureWritten = true;
        current.status = "written";
        current.rows = 1;
        current.objects = 1;
        current.note = KEEP_ORIGINALS_NOTE;
        log(`      ${KEEP_ORIGINALS_NOTE}`);
      }
    }

    // 4. analyses ------------------------------------------------------------
    let analysisRows: readonly Insert<"analyses">[] = [];
    {
      const current = step("analyses");
      log("[4/9] Analyses and masks");
      if (golden === null) {
        current.status = "skipped";
        current.note =
          "Nothing has been analysed yet. A hand written analysis would put invented numbers on a screen that claims to read a real face.";
        log(`      ${current.note}`);
      } else {
        const seed = buildAnalysesSeed(golden);
        analysisRows = seed.rows;
        await putAll(seed.objects);
        await insert("analyses", seed.rows);
        current.status = "written";
        current.rows = seed.rows.length;
        current.objects = seed.objects.length;
        current.note = seed.rows.map((row) => row.kind).join(", ");
      }
    }

    // 5. wardrobe ------------------------------------------------------------
    {
      const current = step("wardrobe");
      log("[5/9] Wardrobe");
      const seed = buildGarmentSeed();
      log(
        "      The six images are SVG silhouettes drawn in code, not photographs. Migration 0006 does not list image/svg+xml on the garments bucket, so an upload here can be refused. The refusal carries the fix.",
      );
      await putAll(seed.objects);
      await insert("garments", seed.rows);
      current.status = "written";
      current.rows = seed.rows.length;
      current.objects = seed.objects.length;
      current.note = "From the checked in fixture in both modes.";
    }

    // 6. looks ---------------------------------------------------------------
    {
      const current = step("looks");
      log("[6/9] Saved looks");
      const rows = buildLookRows();
      await insert("looks", rows);
      current.status = "written";
      current.rows = rows.length;
      current.note = rows
        .map((row) => row.occasion ?? "unknown occasion")
        .join(", ");
    }

    // 7. renders -------------------------------------------------------------
    {
      const current = step("renders");
      log("[7/9] Saved renders");
      if (golden === null) {
        current.status = "skipped";
        current.note =
          "Nothing has been rendered. A stand in image would be a made up try on.";
        log(`      ${current.note}`);
      } else {
        const seed = buildRendersSeed(golden);
        await putAll(seed.objects);
        await insert("renders", seed.rows);
        current.status = "written";
        current.rows = seed.rows.length;
        current.objects = seed.objects.length;
        current.note = seed.rows.map((row) => row.kind).join(", ");
      }
    }

    // 8. aesthetic profile ---------------------------------------------------
    {
      const current = step("aesthetic-profile");
      log("[8/9] Aesthetic profile");
      const row =
        golden === null
          ? buildFixtureProfileRow()
          : buildGoldenProfileRow(golden, analysisRows);
      await insert("aesthetic_profiles", [row]);
      current.status = "written";
      current.rows = 1;
      current.note =
        golden === null
          ? "Built from the checked in fixture. capture_id is null because no photo exists."
          : `Rebuilt from the real analyses through readProfileFacts, derivePalette, and the fallback narrative. capture_id ${captureWritten ? "points at the golden capture" : "is null"}.`;
      log(`      ${current.note}`);
    }

    // 9. product cache -------------------------------------------------------
    {
      const current = step("product-cache");
      log("[9/9] Product cache");
      current.status = "skipped";
      current.note = PRODUCT_CACHE_NOTE;
      log(`      ${PRODUCT_CACHE_NOTE}`);
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    failure = message;
    const running = steps.find((entry) => entry.status === "not run");
    if (running !== undefined) {
      running.status = "failed";
      running.note = message;
    }
  }

  return {
    mode: options.mode,
    dryRun: options.dryRun,
    steps,
    assumptions: golden === null ? [] : [...golden.notes],
    ok: failure === null,
    failure,
  };
}


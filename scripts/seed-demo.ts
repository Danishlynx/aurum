function padRight(value: string, width: number): string {
  return value.length >= width ? value : value + " ".repeat(width - value.length);
}

function padLeft(value: string, width: number): string {
  return value.length >= width ? value : " ".repeat(width - value.length) + value;
}

/** The final table, as lines. Returned rather than printed so it is testable. */
export function summaryLines(report: SeedReport): string[] {
  const idWidth = Math.max(4, ...report.steps.map((step) => step.id.length));
  const statusWidth = Math.max(
    6,
    ...report.steps.map((step) => step.status.length),
  );

  const lines: string[] = [];
  lines.push("");
  lines.push(
    `Summary (mode: ${report.mode}${report.dryRun ? ", dry run" : ""})`,
  );
  lines.push(
    `${padRight("step", idWidth)}  ${padRight("status", statusWidth)}  ${padLeft("rows", 5)}  ${padLeft("objects", 7)}`,
  );
  lines.push(
    `${"-".repeat(idWidth)}  ${"-".repeat(statusWidth)}  ${"-".repeat(5)}  ${"-".repeat(7)}`,
  );
  for (const step of report.steps) {
    lines.push(
      `${padRight(step.id, idWidth)}  ${padRight(step.status, statusWidth)}  ${padLeft(String(step.rows), 5)}  ${padLeft(String(step.objects), 7)}`,
    );
  }

  const written = report.steps.filter((step) => step.status === "written");
  const notWritten = report.steps.filter((step) => step.status !== "written");
  lines.push("");
  lines.push(
    `Written: ${written.length === 0 ? "nothing" : written.map((step) => step.id).join(", ")}`,
  );
  lines.push(
    `Not written: ${notWritten.length === 0 ? "nothing" : notWritten.map((step) => `${step.id} (${step.status})`).join(", ")}`,
  );

  lines.push("");
  lines.push("Notes");
  for (const step of report.steps) {
    if (step.note.length > 0) {
      lines.push(`  ${step.id}: ${step.note}`);
    }
  }

  if (report.assumptions.length > 0) {
    lines.push("");
    lines.push("Assumptions, because the golden run did not record the value");
    for (const assumption of report.assumptions) {
      lines.push(`  ${assumption}`);
    }
  }

  if (report.failure !== null) {
    lines.push("");
    lines.push(`Failed: ${report.failure}`);
  }

  return lines;
}

/** 0 when everything the mode asked for landed, 1 when anything did not. */
export function exitCodeForReport(report: SeedReport): number {
  return report.ok ? 0 : 1;
}


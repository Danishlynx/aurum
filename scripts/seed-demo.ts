/**
 * Only the service role can write the demo profile: the rows are owned by an id
 * that no Supabase session ever holds, so row level security denies every client
 * role by design.
 */
const seedEnvSchema = z.object({
  NEXT_PUBLIC_SUPABASE_URL: z.url(),
  SUPABASE_SERVICE_ROLE_KEY: z.string().min(20),
});

export type SeedEnv = z.infer<typeof seedEnvSchema>;

/**
 * A .env file, as key and value pairs.
 *
 * Pure and exported so it can be unit tested on a literal string. No test ever
 * reads the real .env.local, and no caller ever prints what this returns.
 *
 * An inline "# comment" after an unquoted value is kept rather than stripped: a
 * value may legitimately contain a hash, and silently truncating a key at one
 * would be worse than keeping a comment nobody wrote.
 */
export function parseEnvFile(text: string): Map<string, string> {
  const values = new Map<string, string>();
  for (const rawLine of text.split(/\r?\n/u)) {
    const line = rawLine.trim();
    if (line.length === 0 || line.startsWith("#")) {
      continue;
    }
    const statement = line.startsWith("export ") ? line.slice(7).trim() : line;
    const equals = statement.indexOf("=");
    if (equals <= 0) {
      continue;
    }
    const key = statement.slice(0, equals).trim();
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/u.test(key)) {
      continue;
    }
    let value = statement.slice(equals + 1).trim();
    const quoted =
      value.length >= 2 &&
      ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'")));
    if (quoted) {
      value = value.slice(1, -1);
    }
    values.set(key, value);
  }
  return values;
}

/**
 * Loads .env.local into process.env without overwriting anything already set,
 * so an explicit shell value still wins. Returns how many values were applied.
 * Never returns, logs, or throws a value.
 */
export function loadEnvFile(path: string): number {
  if (!existsSync(path)) {
    return 0;
  }
  let applied = 0;
  for (const [key, value] of parseEnvFile(readFileSync(path, "utf8"))) {
    if (process.env[key] === undefined || process.env[key] === "") {
      process.env[key] = value;
      applied += 1;
    }
  }
  return applied;
}

export function readSeedEnv(): SeedEnv {
  const parsed = seedEnvSchema.safeParse(process.env);
  if (!parsed.success) {
    const missing = parsed.error.issues
      .map((issue) => issue.path.join("."))
      .join(", ");
    throw new SeedError(
      "read environment",
      `Missing or invalid: ${missing}. Fill these in .env.local. Values are never printed.`,
    );
  }
  return parsed.data;
}

/** The origin of a URL, so a log line names the project without its path. */
export function originOf(url: string): string {
  try {
    return new URL(url).origin;
  } catch {
    return "unparseable url";
  }
}


/**
 * Fixture garment id to the uuid its row carries.
 *
 * The fixture ids ("fixture-g01") are readable labels, not uuids, and
 * garments.id is a uuid column. The mapping is by position in the fixture list,
 * so it is stable for as long as the list is, and every look member is remapped
 * through it before it is written.
 */
export function demoGarmentIdByFixtureId(): Map<string, string> {
  const mapping = new Map<string, string>();
  for (const [index, image] of DEMO_FIXTURE_GARMENT_IMAGES.entries()) {
    mapping.set(image.id, demoUuid(ID_BLOCK.garment, index + 1));
  }
  return mapping;
}

export interface GarmentSeed {
  readonly rows: readonly Insert<"garments">[];
  readonly objects: readonly SeedObject[];
}

/**
 * The six garment rows and their images.
 *
 * The attributes come from DEMO_FIXTURE_WARDROBE and the bytes from
 * DEMO_FIXTURE_GARMENT_IMAGES, which is the same function the fixture image
 * route serves, so a seeded wardrobe and a fixture wardrobe show the same six
 * cards with the same six pictures.
 *
 * classification stays null. The column holds "the full model output including
 * confidence" (migration 0003) and no classifier has ever run on these; the
 * card still reads as classified because garmentClassificationStatus in
 * src/lib/shared/wardrobe-view.ts answers from the type, not from this column.
 */
export function buildGarmentSeed(): GarmentSeed {
  const idByFixtureId = demoGarmentIdByFixtureId();
  const svgById = new Map(
    DEMO_FIXTURE_GARMENT_IMAGES.map((image) => [image.id, image.svg] as const),
  );

  const rows: Insert<"garments">[] = [];
  const objects: SeedObject[] = [];

  for (const garment of DEMO_FIXTURE_WARDROBE.garments) {
    const id = idByFixtureId.get(garment.id);
    const svg = svgById.get(garment.id);
    if (id === undefined || svg === undefined) {
      throw new SeedError(
        "build garment rows",
        `The fixture wardrobe holds "${garment.id}", which has no silhouette. Keep DEMO_FIXTURE_WARDROBE and DEMO_FIXTURE_GARMENT_IMAGES in step.`,
      );
    }
    const path = garmentObjectPath(DEMO_OWNER_ID, id, "svg");
    rows.push({
      id,
      user_id: DEMO_OWNER_ID,
      storage_path: path,
      type: garment.type,
      colors: garment.colors.map((color) => ({
        name: color.name,
        hex: color.hex,
      })) as unknown as Json,
      pattern: garment.pattern,
      formality: garment.formality,
      classification: null,
      user_edited: false,
    });
    objects.push({
      bucket: BUCKETS.garments,
      path,
      bytes: new TextEncoder().encode(svg),
      contentType: "image/svg+xml",
    });
  }

  return { rows, objects };
}

/**
 * The two saved looks, docs/07-payments-and-judge-mode.md: "two saved looks for
 * 'Wedding guest' and 'Interview'".
 *
 * Each is the first look of its occasion, which is where a saved look sits in a
 * live read (src/lib/server/looks/compose.ts orders saved looks first), and the
 * members are written through the real toStoredGarments so the column holds
 * exactly what a live save would have put there.
 */
export function buildLookRows(): Insert<"looks">[] {
  const idByFixtureId = demoGarmentIdByFixtureId();
  const rows: Insert<"looks">[] = [];

  for (const [index, occasion] of DEMO_FIXTURE_SAVED_OCCASIONS.entries()) {
    const view = DEMO_FIXTURE_LOOKS[occasion].looks[0];
    if (view === undefined) {
      throw new SeedError(
        "build look rows",
        `The fixture composes no look for "${occasion}", so there is nothing to save for it.`,
      );
    }

    const items: LookItem[] = view.items.map((item) => {
      if (item.source !== "garment") {
        return item;
      }
      const id = idByFixtureId.get(item.garmentId);
      if (id === undefined) {
        throw new SeedError(
          "build look rows",
          `Look "${view.id}" holds garment "${item.garmentId}", which is not in the fixture wardrobe.`,
        );
      }
      return { ...item, garmentId: id };
    });

    rows.push({
      id: demoUuid(ID_BLOCK.look, index + 1),
      user_id: DEMO_OWNER_ID,
      occasion,
      garments: toStoredGarments(items),
      rationale: view.rationale,
      // Nothing has been rendered on the demo face, so the look has no hero
      // try on to point at. A path to an object that does not exist would make
      // the card claim a picture it cannot show.
      render_path: null,
      is_saved: true,
    });
  }

  return rows;
}


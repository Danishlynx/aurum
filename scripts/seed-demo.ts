/** The golden run's own default, scripts/golden-run.ts DEFAULT_HAIRSTYLE_STYLE_ID. */
export const ASSUMED_HAIRSTYLE_STYLE_ID = "textured-crop";

/** Where a params file is looked for, when the run wrote one. */
export function paramsFileFor(step: string): string {
  return `renders/${step}-params.json`;
}

/**
 * The saved renders.
 *
 * params and params_hash go through the same canonical functions the live render
 * layer uses (src/lib/server/renders/params.ts), so re selecting the same shade
 * or the same style on the demo profile finds this row instead of asking for a
 * credit the human does not have. That only works if the parameters here are the
 * ones the run actually sent, which is why a recorded params file always wins
 * and why every assumption is written into the notes rather than left silent.
 *
 * Only the two kinds the golden run buys are handled. Anything else is a failure
 * rather than a row whose hash nobody can reproduce.
 */
export function buildRendersSeed(input: GoldenInput): RendersSeed {
  const rows: Insert<"renders">[] = [];
  const objects: SeedObject[] = [];
  const calls = callsByStep(input.manifest);

  for (const step of ["makeup", "hairstyle"] as const) {
    const call = calls.get(step);
    if (call === undefined) {
      continue;
    }
    const image = call.outputs.find((name) => name.startsWith("renders/"));
    if (image === undefined) {
      throw new SeedError(
        `read the ${step} render`,
        "The call succeeded but wrote no file under renders/, so there is no picture to seed.",
      );
    }

    const id = demoUuid(ID_BLOCK.render, rows.length + 1);
    const path = renderObjectPath(DEMO_OWNER_ID, id, extensionOf(image));
    const paramsFile = paramsFileFor(step);
    const recorded = input.source.exists(paramsFile)
      ? input.source.readJson(paramsFile)
      : null;

    let params: Json;
    let hash: string;

    if (step === "makeup") {
      const parsed = makeupRenderParamsSchema.safeParse(
        recorded ?? recomputedMakeupParams(input),
      );
      if (!parsed.success) {
        throw new SeedError("read the makeup render params", parsed.error.message);
      }
      const stored = canonicalMakeupParams({
        captureId: DEMO_CAPTURE_ID,
        params: parsed.data,
      });
      params = stored as unknown as Json;
      hash = paramsHash("makeup", stored);
      input.notes.push(
        recorded === null
          ? `The makeup shades were recomputed with makeupParamsFrom over the recorded attributes summary and the default categories (${MAKEUP_CATEGORIES.join(", ")}). If the run was given a narrower --makeup-categories, write ${paramsFile} and seed again, or the saved render will not be found by the cache.`
          : `The makeup shades were read from ${paramsFile}.`,
      );
    } else {
      const parsed = hairstyleRenderParamsSchema.safeParse(
        recorded ?? { styleId: ASSUMED_HAIRSTYLE_STYLE_ID },
      );
      if (!parsed.success) {
        throw new SeedError(
          "read the hairstyle render params",
          parsed.error.message,
        );
      }
      const stored = canonicalHairstyleParams({
        captureId: DEMO_CAPTURE_ID,
        params: parsed.data,
      });
      params = stored as unknown as Json;
      hash = paramsHash("hairstyle", stored);
      input.notes.push(
        recorded === null
          ? `No ${paramsFile}, so the hairstyle id was assumed to be the golden run's default "${ASSUMED_HAIRSTYLE_STYLE_ID}". If the run was given --hairstyle-style, write that file and seed again.`
          : `The hairstyle id was read from ${paramsFile}.`,
      );
    }

    rows.push({
      id,
      user_id: DEMO_OWNER_ID,
      kind: step,
      params,
      params_hash: hash,
      storage_path: path,
      provider_task_id: call.taskId ?? null,
      credits_used: unitsOf(call),
      status: "succeeded",
    });
    objects.push({
      bucket: BUCKETS.renders,
      path,
      bytes: input.source.readBytes(image),
      contentType: contentTypeForFile(image),
    });
  }

  return { rows, objects };
}

/**
 * The makeup shades the run sent, recomputed.
 *
 * makeupParamsFrom is imported from scripts/golden-run.ts rather than written
 * again, so there is exactly one place that decides which swatch of each
 * category the demo profile wears. It is deterministic over the recorded
 * attributes summary, so the same summary always produces the same request.
 */
function recomputedMakeupParams(input: GoldenInput): unknown {
  const params = makeupParamsFrom({
    attributesSummary: input.summaries.attributes,
    captureId: DEMO_CAPTURE_ID,
    categories: MAKEUP_CATEGORIES,
  });
  if (params === null) {
    throw new SeedError(
      "rebuild the makeup render params",
      `The run recorded a makeup render but no attributes summary complete enough to say which shades it wore. Write ${paramsFileFor("makeup")} beside the render and seed again.`,
    );
  }
  return { categories: params.categories };
}

/**
 * The aesthetic profile rebuilt from the real analyses.
 *
 * This is the whole point of the golden run: the row a judge reads is built by
 * readProfileFacts, derivePalette, and buildFallbackNarrative, which are the
 * same three the live app builds a profile with
 * (src/lib/server/profile/build.ts). Nothing here restates a number that those
 * functions can derive, so the seeded profile and a live profile cannot drift.
 *
 * The one thing the live path does that this cannot is call Claude for the
 * reading. If a reading.json sits beside the run, it is used and its model id is
 * stored; otherwise the deterministic fallback writes it, and reading_model says
 * "fallback/..." so the report screen reports it as the fallback, truthfully.
 */
export function buildGoldenProfileRow(
  input: GoldenInput,
  analyses: readonly Insert<"analyses">[],
): Insert<"aesthetic_profiles"> {
  const rows: Analysis[] = analyses.map((row) => ({
    // readProfileFacts never reads the analysis id, so an insert row that has
    // not been given one yet still reads correctly here.
    id: row.id ?? "",
    capture_id: row.capture_id,
    user_id: row.user_id,
    kind: row.kind,
    status: "succeeded",
    provider_task_id: row.provider_task_id ?? null,
    raw: row.raw ?? null,
    summary: row.summary ?? null,
    mask_paths: row.mask_paths ?? null,
    credits_used: row.credits_used ?? 0,
    error: null,
    created_at: "",
    updated_at: "",
  }));

  const facts = readProfileFacts({ captureId: DEMO_CAPTURE_ID, analyses: rows });

  const palette =
    facts.skinToneHex === null || facts.undertone === null
      ? null
      : derivePalette({
          skinToneHex: facts.skinToneHex,
          undertone: facts.undertone,
          eyeColorHex: facts.eyeColorHex,
          hairColorHex: facts.hairColorHex,
          fitzpatrick: facts.fitzpatrick,
        });

  const narrative = buildFallbackNarrative(facts);
  let reading = narrative?.reading ?? null;
  let readingModel = narrative?.readingModel ?? null;

  if (input.source.exists(RECORDED_READING_FILE)) {
    const parsed = recordedReadingSchema.safeParse(
      input.source.readJson(RECORDED_READING_FILE),
    );
    if (!parsed.success) {
      throw new SeedError(`read ${RECORDED_READING_FILE}`, parsed.error.message);
    }
    reading = parsed.data.reading;
    readingModel = parsed.data.readingModel;
    input.notes.push(`The reading was read from ${RECORDED_READING_FILE}.`);
  }

  return {
    user_id: DEMO_OWNER_ID,
    capture_id: DEMO_CAPTURE_ID,
    skin_type_zones: {
      t_zone: facts.zones.tZone,
      cheeks: facts.zones.cheeks,
    } as Json,
    concerns: facts.ranked.map((concern) => ({
      key: concern.key,
      score: concern.score,
      rank: concern.rank,
      mask_path: facts.maskPathByKey.get(concern.key) ?? null,
    })) as unknown as Json,
    skin_age: facts.skinAge,
    fitzpatrick: facts.fitzpatrick,
    skin_tone_hex: facts.skinToneHex,
    undertone: facts.undertone,
    undertone_source: facts.undertone === null ? null : "detected",
    eye_color_hex: facts.eyeColorHex,
    hair_color_hex: facts.hairColorHex,
    face_shape: facts.faceShape,
    hair_type: null,
    saved_hair_style_id: null,
    saved_hair_color_name: null,
    season: palette?.season ?? null,
    palette: palette === null ? null : (palette as unknown as Json),
    reading,
    reading_model: readingModel,
    version: 1,
  };
}

function fileStem(path: string): string {
  const file = path.split(/[\\/]/u).pop() ?? path;
  const dot = file.lastIndexOf(".");
  return dot === -1 ? file : file.slice(0, dot);
}


/**
 * Seeds the demo profile that judge sessions read, and that every screenshot on
 * the Devpost page is taken from.
 *
 * Spec: docs/07-payments-and-judge-mode.md, "Demo profile". The demo owner is a
 * fixed id rather than an auth user, exactly like a judge session, so the same
 * read paths serve it.
 *
 * Run it with one of:
 *
 *     npm run seed:demo -- --from-fixtures
 *     npm run seed:demo -- --from-golden evals/fixtures/golden --image path\to\selfie.jpg
 *     npm run seed:demo -- --from-fixtures --dry-run
 *
 * The npm script carries "--conditions=react-server". Every module this script
 * imports out of src/lib/server opens with import "server-only", whose default
 * export throws outside a React Server Component. The react-server condition
 * resolves that package to its empty module instead, which is the same escape
 * the eval suites take with vi.mock("server-only").
 *
 * WHY TWO MODES
 *
 * The human holds 40 Perfect Corp trial units in total. Judges therefore get no
 * live analysis at all: the whole judge experience serves this seeded demo
 * profile, and the units are spent once, on the founder's own selfie, in the
 * golden run. That leaves two moments where the demo profile has to exist:
 *
 * 1. --from-fixtures, which works today and needs no credits. It seeds the
 *    checked in demo fixture (src/lib/server/profile/demo-fixture*.ts): the
 *    aesthetic profile, the six garment wardrobe, and the two saved looks.
 *    There is no capture, no analysis, no mask, and no render, because none of
 *    those exist yet and a stand in for a face or a try on would be a made up
 *    picture (docs/06-safety-privacy.md, "Grounding and honesty").
 * 2. --from-golden <dir>, which runs after scripts/golden-run.ts has written its
 *    output directory. It seeds everything above and, in addition, the real
 *    capture, the real analyses with their masks, the real renders, and an
 *    aesthetic profile rebuilt from those analyses through the same functions
 *    the live app builds a profile with, so the seeded row and a live row cannot
 *    drift. <dir> is the golden run's --out folder, and the mode reads that
 *    script's own manifest.json rather than a format of its own.
 *
 * Both modes read the fixture data through the very modules the fixture views
 * are built from, never through a second copy of the numbers.
 *
 * CREDITS
 *
 * This script never calls a provider. It writes rows and objects, nothing else.
 *
 * IDEMPOTENCY, and the choice behind it
 *
 * Delete then insert, scoped to the demo owner id, in one documented order. Not
 * upsert: every row and every object under this owner is generated by this
 * script, so the fixture is the whole truth about it, and an upsert would leave
 * behind rows and objects from an older fixture that no longer has their ids.
 * Deleting first means a re run always lands on exactly what the current
 * fixture describes. Rows go in reverse dependency order (analyses before the
 * captures they reference, the profile before the capture its capture_id points
 * at) and come back in forward order.
 *
 * SECRETS
 *
 * .env.local is read by this script and never printed. No key, no token, and no
 * part of one reaches stdout or stderr; the only environment value ever echoed
 * is the origin of the Supabase project URL, which is public by construction
 * (it is the NEXT_PUBLIC_ one).
 */


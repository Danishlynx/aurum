/**
 * The analyses rows and their masks.
 *
 * One row per summary the golden run recorded, in the order db/types.ts lists
 * the kinds. The step a kind came from is looked up through GOLDEN_STEPS, which
 * is golden-run.ts's own table, so the two scripts cannot disagree about which
 * call produced which analysis.
 *
 * The mask object path is rebuilt with the real maskPath helper, and the file
 * stem becomes the concern key, which is the convention
 * src/lib/server/profile/facts.ts reads a mask back by (concernKeyFromMaskPath).
 * A mask named anything else is still uploaded and still stored on the row; it
 * simply will not attach to a concern, which is what would happen to it in a
 * live run too.
 */
export function buildAnalysesSeed(input: GoldenInput): AnalysesSeed {
  const rows: Insert<"analyses">[] = [];
  const objects: SeedObject[] = [];
  const calls = callsByStep(input.manifest);

  const stepForKind = new Map<AnalysisKind, string>();
  for (const [step, definition] of Object.entries(GOLDEN_STEPS)) {
    if (definition.kind === "analysis") {
      stepForKind.set(definition.analysisKind, step);
    }
  }

  for (const kind of ANALYSIS_KINDS) {
    const summary = input.summaries[kind];
    if (summary === undefined || summary === null) {
      continue;
    }
    const call = calls.get(stepForKind.get(kind) ?? "");
    const outputs = call?.outputs ?? [];

    const maskPaths: string[] = [];
    for (const file of outputs.filter((name) => name.startsWith("masks/"))) {
      const path = maskPath(
        DEMO_OWNER_ID,
        DEMO_CAPTURE_ID,
        fileStem(file),
        extensionOf(file),
      );
      maskPaths.push(path);
      objects.push({
        bucket: BUCKETS.masks,
        path,
        bytes: input.source.readBytes(file),
        contentType: contentTypeForFile(file),
      });
    }

    const rawFile = outputs.find((name) => name.startsWith("raw/"));

    rows.push({
      id: demoUuid(ID_BLOCK.analysis, rows.length + 1),
      capture_id: DEMO_CAPTURE_ID,
      user_id: DEMO_OWNER_ID,
      kind,
      status: "succeeded",
      provider_task_id: call?.taskId ?? null,
      raw: rawFile === undefined ? null : (input.source.readJson(rawFile) as Json),
      summary: summary as Json,
      mask_paths: maskPaths as unknown as Json,
      credits_used: unitsOf(call),
      error: null,
    });
  }

  if (rows.length === 0) {
    throw new SeedError(
      "build analyses rows",
      "The golden run recorded no analysis summary, so there is nothing to build a profile from.",
    );
  }

  return { rows, objects };
}


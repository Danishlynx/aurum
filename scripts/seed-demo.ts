/** A succeeded call, by golden run step name. */
function callsByStep(manifest: GoldenManifest): Map<string, GoldenManifest["calls"][number]> {
  const found = new Map<string, GoldenManifest["calls"][number]>();
  for (const call of manifest.calls) {
    if (call.state === "succeeded") {
      found.set(call.step, call);
    }
  }
  return found;
}

/** What one call actually cost, measured first, then the cost table, then zero. */
function unitsOf(call: GoldenManifest["calls"][number] | undefined): number {
  return call?.measuredUnits ?? call?.tableUnits ?? 0;
}


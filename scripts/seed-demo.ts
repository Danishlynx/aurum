/**
 * Where the golden run's files are read from.
 *
 * An interface rather than a directory string, so a unit test can hand the
 * seeder an in memory run and never touch a disk. An absolute path passes
 * through unchanged, which is how the selfie is read from outside the
 * directory.
 */
export interface FileSource {
  readonly label: string;
  exists(path: string): boolean;
  readJson(path: string): unknown;
  readBytes(path: string): Uint8Array;
}

export function diskSource(root: string): FileSource {
  const full = (path: string): string => resolve(root, path);
  const readFile = (path: string): Buffer => {
    if (!existsSync(full(path))) {
      throw new SeedError("read golden file", `${path} is missing.`);
    }
    return readFileSync(full(path));
  };
  return {
    label: root,
    exists: (path) => existsSync(full(path)),
    readJson(path) {
      /*
       * The leading byte order mark is stripped. Windows editors and PowerShell
       * both write one by default, JSON.parse rejects it, and "Unexpected token"
       * is a useless thing to hand an operator holding a file they just saved.
       */
      const text = readFile(path).toString("utf8").replace(/^\uFEFF/u, "");
      try {
        return JSON.parse(text) as unknown;
      } catch (error) {
        throw new SeedError(
          `read ${path}`,
          error instanceof Error ? error.message : "it is not valid JSON.",
        );
      }
    },
    readBytes(path) {
      return new Uint8Array(readFile(path));
    },
  };
}

export function loadGoldenManifest(source: FileSource): GoldenManifest {
  const parsed = goldenManifestSchema.safeParse(source.readJson("manifest.json"));
  if (!parsed.success) {
    const where = parsed.error.issues
      .map((issue) => `${issue.path.join(".")}: ${issue.message}`)
      .join("; ");
    throw new SeedError("read manifest.json", where);
  }
  return parsed.data;
}

export function loadGoldenSummaries(
  source: FileSource,
  manifest: GoldenManifest,
): GoldenSummaries {
  if (manifest.fixtureFile === null) {
    throw new SeedError(
      "read the analyses fixture",
      "manifest.json has fixtureFile null, which means the golden run produced no skin analysis. There is nothing to build a profile from, so nothing is seeded.",
    );
  }
  const parsed = goldenFixtureSummariesSchema.safeParse(
    source.readJson(manifest.fixtureFile),
  );
  if (!parsed.success) {
    throw new SeedError(`read ${manifest.fixtureFile}`, parsed.error.message);
  }
  const summaries = parsed.data.summaries;
  return {
    skin: summaries.skin ?? undefined,
    fitzpatrick: summaries.fitzpatrick ?? undefined,
    attributes: summaries.attributes ?? undefined,
    face_shape: summaries.face_shape ?? undefined,
    hair_type: summaries.hair_type ?? undefined,
  };
}

/** The names a selfie is looked for under, when --image was not given. */
export const CAPTURE_IMAGE_CANDIDATES: readonly string[] = [
  "capture.jpg",
  "capture.jpeg",
  "capture.png",
  "capture.webp",
];

export function findCaptureImage(
  source: FileSource,
  imagePath: string | null,
): string {
  if (imagePath !== null) {
    return imagePath;
  }
  for (const candidate of CAPTURE_IMAGE_CANDIDATES) {
    if (source.exists(candidate)) {
      return candidate;
    }
  }
  throw new SeedError(
    "find the golden selfie",
    `The golden run records the selfie's hash but never copies the file, and none of ${CAPTURE_IMAGE_CANDIDATES.join(", ")} is in ${source.label}. Pass the same path the run was given: --image <path>.`,
  );
}

/** The extension a captures, masks, or renders object is stored under. */
const EXTENSION_BY_CONTENT_TYPE: Readonly<Record<string, string>> = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
};

export function extensionForContentType(contentType: string): string {
  const extension = EXTENSION_BY_CONTENT_TYPE[contentType.toLowerCase()];
  if (extension === undefined) {
    throw new SeedError(
      "read the capture content type",
      `The buckets accept ${BUCKET_ALLOWED_MIME.join(", ")} (migration 0006) and the run recorded "${contentType}".`,
    );
  }
  return extension;
}


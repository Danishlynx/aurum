const CONTENT_TYPE_BY_EXTENSION: Readonly<Record<string, string>> = {
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".png": "image/png",
  ".webp": "image/webp",
  ".svg": "image/svg+xml",
};

/** The allow list migration 0006 puts on all four buckets. */
const BUCKET_ALLOWED_MIME: readonly string[] = [
  "image/jpeg",
  "image/png",
  "image/webp",
];

export function contentTypeForFile(fileName: string): string {
  const extension = extname(fileName).toLowerCase();
  const contentType = CONTENT_TYPE_BY_EXTENSION[extension];
  if (contentType === undefined) {
    throw new SeedError(
      `read ${fileName}`,
      `Unsupported image extension "${extension}". Use .jpg, .png, or .webp.`,
    );
  }
  return contentType;
}

/** The extension without its dot, for building an object path from a file. */
function extensionOf(fileName: string): string {
  return extname(fileName).toLowerCase().replace(/^\./u, "");
}


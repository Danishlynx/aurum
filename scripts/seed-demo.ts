/**
 * What scripts/golden-run.ts writes into its output directory, read back.
 *
 * This schema is deliberately a reader of that script's real output rather than
 * a contract of its own, because the golden run is the thing that costs money
 * and it therefore gets to decide the file layout. What it writes:
 *
 *     manifest.json          the run record: the image header, the spend, and
 *                            one entry per provider call with its outputs
 *     <fixtureId>.json       the analyses fixture, holding the normalized
 *                            summary per analysis kind
 *     raw/<step>.json        the validated provider response, bytes stripped
 *     masks/<concern>.<ext>  one mask per concern the skin analysis returned
 *     renders/<step>-N.<ext> the render images
 *
 * Unknown keys are dropped rather than rejected, so the golden run can add to
 * its manifest without breaking this reader.
 *
 * THREE THINGS THE GOLDEN RUN DOES NOT WRITE, and how each is resolved. All
 * three are open items worth closing in golden-run.ts rather than here:
 *
 * 1. A copy of the selfie. It hashes the file at --image and never copies it.
 *    So this script takes --image too, and falls back to a capture.<ext> file
 *    sitting in the golden directory.
 * 2. The makeup shade choices it sent. They are recomputed here with
 *    makeupParamsFrom, the same function the run used, over the same recorded
 *    attributes summary. That reproduces the exact request as long as the run
 *    used the default --makeup-categories; a run with a narrower set needs a
 *    renders/makeup-params.json beside the image, which this reader prefers
 *    whenever it exists.
 * 3. The hairstyle id it sent. Same answer: renders/hairstyle-params.json wins,
 *    and without it the golden run's own default is assumed and printed.
 */
export const goldenManifestSchema = z.object({
  recordedOn: z.string().min(1),
  captureId: z.string().min(1),
  /** Name of the analyses fixture file, or null when no skin analysis landed. */
  fixtureFile: z.string().min(1).nullable(),
  image: z.object({
    sha256: z.string().regex(/^[0-9a-f]{64}$/u),
    contentType: z.string().min(1),
    width: z.number().int().positive().nullable().optional(),
    height: z.number().int().positive().nullable().optional(),
    byteLength: z.number().int().positive().optional(),
  }),
  calls: z.array(
    z.object({
      step: z.string().min(1),
      taskId: z.string().min(1).nullable().optional(),
      state: z.string().min(1),
      tableUnits: z.number().int().min(0).nullable().optional(),
      measuredUnits: z.number().int().min(0).nullable().optional(),
      outputs: z.array(z.string().min(1)),
      error: z.string().nullable().optional(),
    }),
  ),
});


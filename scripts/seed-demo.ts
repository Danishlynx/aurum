export interface SeedObject {
  readonly bucket: BucketName;
  readonly path: string;
  readonly bytes: Uint8Array;
  readonly contentType: string;
}

/**
 * Everything this script does to Supabase, as five operations.
 *
 * The seam exists so the seeding logic can be exercised with a recording double
 * in a unit test: no network, no keys, no project. Every method throws
 * SeedError on failure rather than returning one, because a half seeded demo
 * profile is not a state anything should carry on from.
 */
export interface SeedWriter {
  deleteOwnedRows(table: SeedTableName, ownerId: string): Promise<void>;
  insertRows<T extends SeedTableName>(
    table: T,
    rows: readonly Insert<T>[],
  ): Promise<void>;
  listObjects(bucket: BucketName, prefix: string): Promise<string[]>;
  removeObjects(bucket: BucketName, paths: readonly string[]): Promise<void>;
  putObject(object: SeedObject): Promise<void>;
}

/** The shape of one PostgREST query builder, narrowed to what is used here. */
interface PostgrestLike {
  insert(rows: unknown): PromiseLike<{ error: { message: string } | null }>;
  delete(): {
    eq(column: string, value: string): PromiseLike<{ error: { message: string } | null }>;
  };
}

/** Folders come back from storage.list with a null id, files with a real one. */
interface StorageEntry {
  readonly name: string;
  readonly id: string | null;
}

const MAX_STORAGE_DEPTH = 2;

export function supabaseWriter(
  client: SupabaseClient<Database, "public">,
): SeedWriter {
  /*
   * One cast, here, and a comment saying why. The table name is a union of
   * literals, so client.from(name) is a union of differently typed builders and
   * calling insert on the union does not typecheck. Row shapes are still fully
   * checked, at the call sites, because insertRows is generic over the table
   * name and takes Insert<T> from src/lib/server/db/types.ts.
   */
  const table = (name: SeedTableName): PostgrestLike =>
    client.from(name) as unknown as PostgrestLike;

  async function walk(
    bucket: BucketName,
    prefix: string,
    depth: number,
    found: string[],
  ): Promise<void> {
    if (depth > MAX_STORAGE_DEPTH) {
      return;
    }
    const { data, error } = await client.storage
      .from(bucket)
      .list(prefix, { limit: 1000 });
    if (error !== null) {
      throw new SeedError(`list ${bucket}/${prefix}`, error.message);
    }
    for (const entry of (data ?? []) as unknown as StorageEntry[]) {
      const path = `${prefix}/${entry.name}`;
      if (entry.id === null) {
        await walk(bucket, path, depth + 1, found);
        continue;
      }
      found.push(path);
    }
  }

  return {
    async deleteOwnedRows(name, ownerId) {
      const { error } = await table(name).delete().eq("user_id", ownerId);
      if (error !== null) {
        throw new SeedError(`delete from ${name}`, error.message);
      }
    },

    async insertRows(name, rows) {
      if (rows.length === 0) {
        return;
      }
      const { error } = await table(name).insert(rows);
      if (error !== null) {
        throw new SeedError(`insert into ${name}`, error.message);
      }
    },

    async listObjects(bucket, prefix) {
      const found: string[] = [];
      await walk(bucket, prefix, 0, found);
      return found;
    },

    async removeObjects(bucket, paths) {
      if (paths.length === 0) {
        return;
      }
      const { error } = await client.storage.from(bucket).remove([...paths]);
      if (error !== null) {
        throw new SeedError(`remove from ${bucket}`, error.message);
      }
    },

    async putObject(object) {
      const { error } = await client.storage
        .from(object.bucket)
        .upload(object.path, object.bytes, {
          contentType: object.contentType,
          upsert: true,
        });
      if (error === null) {
        return;
      }
      const mimeRejected =
        !BUCKET_ALLOWED_MIME.includes(object.contentType) &&
        /mime|content type|content_type/iu.test(error.message);
      throw new SeedError(
        `upload to ${object.bucket}`,
        mimeRejected ? `${error.message}. ${GARMENT_MIME_REMEDIATION}` : error.message,
      );
    },
  };
}

